"""
Protocols and structural typing interfaces for Reserve Juggler.

Conforms to Section 3: Shared Integration Contract.
Uses Python protocols to ensure clean structural compatibility with Team 1's
canonical contracts and Team 3's learning/audit pipelines without importing
or defining duplicate canonical schema modules.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any, Mapping, Optional, Protocol, Sequence, runtime_checkable


@runtime_checkable
class Obligation(Protocol):
    """Obligation protocol representing scheduled payouts or settlements."""

    due_time: datetime
    amount: float
    description: str
    is_mandatory: bool


@runtime_checkable
class AssetPosition(Protocol):
    """Asset position representing allocated capital across tiers."""

    asset_id: str
    tier: int  # 1: Cash/Repo, 2: Sovereign Bonds, 3: Equities
    market_value: float
    liquidatable_value: float
    availability: datetime
    maturity: Optional[datetime]
    settlement_delay_hours: float
    annual_yield: float  # Decimal rate (e.g. 0.048 for 4.8%)
    exit_fees: float  # Early liquidation penalty rate (e.g. 0.005 for 0.5%)
    haircut: float  # Liquidation haircut rate (e.g. 0.02 for 2.0%)
    duration: float  # Duration in years (e.g. 2.0 for 2-year sovereign bonds)
    volatility: float  # Annualized volatility (e.g. 0.18 for growth equities)
    cost_basis: float  # Tax cost basis
    instrument_type: str  # 'cash', 'repo', 'bond', 'equity'


@runtime_checkable
class ForecastPoint(Protocol):
    """Point forecast across probabilistic quantiles and horizons."""

    forecast_horizon: float  # Horizon in hours
    deposit_p10: float
    deposit_p50: float
    deposit_p90: float
    withdrawal_p10: float
    withdrawal_p50: float
    withdrawal_p90: float
    conservative_outflow: float  # Conservative net cumulative outflow estimate
    reliability_metadata: Mapping[str, Any]


@runtime_checkable
class ForecastBundle(Protocol):
    """Bundle containing forecasts, scenarios, and health metadata."""

    point_forecasts: Sequence[ForecastPoint]
    scenarios: Mapping[str, Any]
    timestamp: datetime
    quality_status: str  # 'HEALTHY', 'DEGRADED', 'STALE', 'CRITICAL'
    model_versions: Mapping[str, str]


@runtime_checkable
class RiskSignal(Protocol):
    """Risk signal generated by market scanners or anomaly detectors."""

    source: str
    severity: str  # 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL'
    confidence: float  # 0.0 to 1.0
    timestamp: datetime
    supporting_evidence: Mapping[str, Any]
    scenario_tags: Sequence[str]


@runtime_checkable
class DecisionRecord(Protocol):
    """Canonical decision record with JSON-serializable action and reasoning."""

    decision_id: str
    timestamp: datetime
    selected_action: Mapping[str, Any]
    alternatives: Sequence[Mapping[str, Any]]
    score: Mapping[str, Any]
    reserve: Mapping[str, Any]
    eligible_surplus: float
    cost_breakdown: Mapping[str, float]
    hard_gate_results: Mapping[str, Any]
    reason_codes: Sequence[str]

    def to_dict(self) -> dict[str, Any]:
        """Convert decision record to JSON-serializable dictionary."""
        ...


@runtime_checkable
class ExecutionOutcome(Protocol):
    """Post-execution feedback from settlement and ledger."""

    realized_cash_movements: float
    costs: float
    penalties: float
    losses: float
    liquidity_shortfalls: float
    metadata: Mapping[str, Any]


@runtime_checkable
class LearningEvent(Protocol):
    """Standardized event for Team 3 audit, feedback, and reinforcement learning."""

    versioned_event_type: str
    source_module: str
    timestamp: datetime
    correlation_id: str
    structured_data: Mapping[str, Any]
    model_policy_versions: Mapping[str, str]

    def to_dict(self) -> dict[str, Any]:
        """Convert learning event to JSON-serializable dictionary."""
        ...


@runtime_checkable
class TreasuryState(Protocol):
    """Treasury state protocol capturing cash, assets, and liabilities."""

    timestamp: datetime
    available_cash: float
    asset_positions: Sequence[AssetPosition]
    future_obligations: Sequence[Obligation]
    credit_availability: float
    credit_limit: float
    credit_apr: float  # Decimal rate (e.g. 0.12 for 12.0%)
    data_quality_warnings: Sequence[str]
